def classify(text):

    emb = embedder.encode([text])
    emb = torch.tensor(emb, dtype=torch.float32)

    logits = model(emb)
    pred = torch.argmax(logits).item()

    labels = ["PASS", "WARN", "FAIL", "INFO"]

    return labels[pred]

